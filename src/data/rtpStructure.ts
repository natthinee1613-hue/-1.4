// Helper: Flatten all subordinate divisions into an exhaustive table array
export function getAllDivisionsFlat(): DivisionItem[] {
  const list: DivisionItem[] = [];

  RTP_BUREAUS_DATA.forEach((bureau) => {
    bureau.subDivisions.forEach((subDiv) => {
      const cleanName = subDiv.replace(/\(.*?\)/g, '').trim();
      const acronymMatch = subDiv.match(/\((.*?)\)/);
      const shortName = acronymMatch ? acronymMatch[1].trim() : cleanName;

      // Classify category
      let category = 'ปฏิบัติการ';
      if (subDiv.includes('อำนวยการ') || subDiv.includes('ฝอ.') || subDiv.includes('บก.อก.')) {
        category = 'อำนวยการ';
      } else if (subDiv.includes('สืบสวน') || subDiv.includes('สส.')) {
        category = 'สืบสวนสอบสวน';
      } else if (subDiv.includes('ฝึกอบรม') || subDiv.includes('ศฝร.') || subDiv.includes('วิทยาลัย') || subDiv.includes('คณะ')) {
        category = 'การศึกษา/ฝึกอบรม';
      } else if (subDiv.includes('ตรวจคนเข้าเมือง') || subDiv.includes('ตม.')) {
        category = 'ตรวจคนเข้าเมือง';
      } else if (subDiv.includes('พิสูจน์หลักฐาน') || subDiv.includes('พฐ') || subDiv.includes('นิติเวช')) {
        category = 'นิติวิทยาศาสตร์/พิสูจน์หลักฐาน';
      } else if (subDiv.includes('จราจร') || subDiv.includes('บก.จร.')) {
        category = 'จราจร';
      } else if (subDiv.includes('สปพ.') || subDiv.includes('191') || subDiv.includes('อคฝ.') || subDiv.includes('นเรศวร') || subDiv.includes('ปฏิบัติการพิเศษ')) {
        category = 'ปฏิบัติการพิเศษ/อารักขา';
      } else if (subDiv.includes('ภูธรจังหวัด') || subDiv.includes('ภ.จว.') || subDiv.includes('บก.น.')) {
        category = 'ป้องกันปราบปรามพื้นที่';
      } else if (subDiv.includes('แพทย์') || subDiv.includes('พยาบาล') || subDiv.includes('รพ.')) {
        category = 'การแพทย์และพยาบาล';
      } else if (subDiv.includes('ตรวจราชการ') || subDiv.includes('กต.')) {
        category = 'จเรตำรวจ/ตรวจสอบ';
      } else if (subDiv.includes('เทคโนโลยี') || subDiv.includes('สื่อสาร') || subDiv.includes('ไซเบอร์') || subDiv.includes('สอท.')) {
        category = 'เทคโนโลยีและไซเบอร์';
      }

      list.push({
        id: `${bureau.id}-${cleanName}`,
        bureauId: bureau.id,
        bureauCode: bureau.code,
        bureauName: bureau.fullName,
        name: cleanName,
        shortName: shortName,
        displayName: subDiv,
        group: bureau.group,
        category,
        jurisdiction: bureau.jurisdiction,
        description: `${cleanName} ในสังกัด ${bureau.fullName} (${bureau.code})`,
      });
    });
  });

  return list;
}


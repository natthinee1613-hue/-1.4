// Helper: Match officers from database to a division string
export function getOfficersForDivision(
  divString: string,
  bureau: PoliceBureauNode,
  allOfficers: PoliceOfficer[]
): {
  matchedDivisionName: string;
  officers: PoliceOfficer[];
  cleanName: string;
  acronym: string;
} {
  const cleanName = divString.replace(/\(.*?\)/g, '').trim();
  const acronymMatch = divString.match(/\((.*?)\)/);
  const acronym = acronymMatch ? acronymMatch[1].trim() : '';

  // 1. Exact match
  const direct = allOfficers.filter((o) => o.division === divString);
  if (direct.length > 0) {
    return { matchedDivisionName: divString, officers: direct, cleanName, acronym };
  }

  // 2. Fuzzy match against officer's division
  const matched = allOfficers.filter((o) => {
    const oDiv = o.division?.trim() || '';
    if (!oDiv) return false;

    if (oDiv === cleanName) return true;
    if (cleanName && (oDiv.includes(cleanName) || cleanName.includes(oDiv))) return true;

    // Special match for headquarters / commander's office
    if (
      (divString.includes('สำนักงานผู้บังคับบัญชา') || divString.includes('ฝ่ายอำนวยการ')) &&
      (oDiv === bureau.id || oDiv === bureau.code)
    ) {
      return true;
    }

    // Match acronym
    if (acronym && (oDiv.includes(acronym) || o.subDivision?.includes(acronym))) {
      return true;
    }

    return false;
  });

  let canonicalName = divString;
  if (matched.length > 0) {
    canonicalName = matched[0].division;
  } else if (cleanName) {
    canonicalName = cleanName;
  }

  return { matchedDivisionName: canonicalName, officers: matched, cleanName, acronym };
}

